"""
Streamlit RAG comparison app.

Three answer modes for every user question:
  1. Naive       — no context, plain LLM call via Ollama
  2. Simple RAG  — context from trace.json, regenerated by
                   neo4j_kg_retrieval_llamaindex.py for the current query
  3. Advanced RAG — context from results/retrieved_nodes.json, regenerated by
                   definability.py (which reads the fresh trace.json)
"""

from __future__ import annotations

import json
import subprocess
import tempfile
import sys
from pathlib import Path
from typing import Any

import requests
import streamlit as st

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
BASE_DIR = Path(__file__).parent
RETRIEVAL_SCRIPT    = BASE_DIR / "neo4j_kg_retrieval_llamaindex.py"
TEXT2CYPHER_SCRIPT  = BASE_DIR / "text2cypher.py"
DEFINABILITY_SCRIPT = BASE_DIR / "definability.py"


def _workdir() -> Path:
    """Private working directory of the current browser session.

    Each session writes its own trace and SADR results, so concurrent users
    never read each other's files.
    """
    if "workdir" not in st.session_state:
        st.session_state["workdir"] = tempfile.mkdtemp(prefix="sadr-session-")
    return Path(st.session_state["workdir"])


def _trace_path() -> Path:
    return _workdir() / "trace.json"


def _definability_dir() -> Path:
    return _workdir() / "results"


def _definability_out() -> Path:
    return _definability_dir() / "retrieved_nodes.json"

# ---------------------------------------------------------------------------
# Retrieval pipeline
# ---------------------------------------------------------------------------

def run_retrieval(query: str) -> tuple[bool, str]:
    """
    Run neo4j_kg_retrieval_llamaindex.py to regenerate trace.json.
    Returns (success, error_message).
    """
    result = subprocess.run(
        [
            sys.executable,
            str(RETRIEVAL_SCRIPT),
            "retrieve",
            "--query", query,
            "--out", str(_trace_path()),
        ],
        cwd=str(BASE_DIR),
        capture_output=True,
        text=True,
        timeout=120,
    )
    if result.returncode != 0:
        return False, result.stderr or result.stdout
    return True, ""


def run_text2cypher_retrieval(query: str, model: str) -> tuple[bool, str]:
    """
    Run text2cypher.py to regenerate trace.json using an LLM-generated Cypher query.
    Returns (success, error_message).
    """
    result = subprocess.run(
        [
            sys.executable,
            str(TEXT2CYPHER_SCRIPT),
            "--query", query,
            "--model", model,
            "--out", str(_trace_path()),
        ],
        cwd=str(BASE_DIR),
        capture_output=True,
        text=True,
        timeout=120,
    )
    if result.returncode != 0:
        return False, result.stderr or result.stdout
    return True, ""


def run_definability() -> tuple[bool, str]:
    """
    Run definability.py to regenerate results/retrieved_nodes.json.
    It reads the session's trace.json and writes the session's results/retrieved_nodes.json.
    Returns (success, error_message).
    """
    result = subprocess.run(
        [sys.executable, str(DEFINABILITY_SCRIPT),
         "--trace", str(_trace_path()), "--out-dir", str(_definability_dir())],
        cwd=str(BASE_DIR),
        capture_output=True,
        text=True,
        timeout=900,
    )
    if result.returncode != 0:
        return False, result.stderr or result.stdout
    return True, ""


def regenerate_json_files(
    query: str, model: str, retrieval_mode: str, status_area
) -> tuple[bool, bool]:
    """
    Run retrieval (embedding or text2cypher) + definability for the given query.
    Updates status_area with live progress messages.
    Returns (trace_ok, definability_ok).
    """
    # Step 1 — retrieval → trace.json
    if retrieval_mode == "text2cypher":
        status_area.info("Step 1/2 — Running Text2Cypher retrieval (text2cypher.py)…")
        trace_ok, err = run_text2cypher_retrieval(query, model)
        if not trace_ok:
            status_area.warning(
                f"Text2Cypher retrieval failed — falling back to embedding retrieval.\n"
                f"```\n{err}\n```"
            )
            trace_ok, err = run_retrieval(query)
    else:
        status_area.info("Step 1/2 — Running vector retrieval (neo4j_kg_retrieval_llamaindex.py)…")
        trace_ok, err = run_retrieval(query)

    if not trace_ok:
        status_area.error(f"Retrieval script failed:\n```\n{err}\n```")
        return False, False

    # Step 2 — definability → results/retrieved_nodes.json
    status_area.info("Step 2/2 — Running definability algorithm (definability.py)…")
    def_ok, err = run_definability()
    if not def_ok:
        status_area.warning(
            f"Definability script failed (Advanced RAG will be unavailable):\n```\n{err}\n```"
        )
        return True, False

    status_area.success("Both JSON files regenerated successfully.")
    return True, True


