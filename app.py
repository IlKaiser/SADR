def _load_json(path: Path) -> Any:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def build_simple_rag_context() -> str:
    """Build readable context from trace.json (seed nodes + graph triplets)."""
    data = _load_json(_trace_path())
    lines: list[str] = []

    original_query = data.get("query", "")
    if original_query:
        lines.append(f"[Query: \"{original_query}\"]\n")

    # If trace.json was produced by Text2Cypher, show the query and direct results
    cypher = data.get("generated_cypher", "")
    if cypher:
        lines.append(f"[Retrieved via Cypher]\n```\n{cypher}\n```\n")

    cypher_nodes = data.get("cypher_results", {}).get("nodes", [])
    if cypher_nodes:
        lines.append("## Cypher Query Results")
        for node in cypher_nodes:
            props = node.get("properties", {})
            label = node.get("label", "")
            title  = props.get("title", "")
            name   = props.get("name", "")
            genre  = props.get("genre", "")
            heading = title or name or genre or node.get("id", "?")
            line = f"- **{heading}**"
            if label:
                line += f"  [{label}]"
            if not title and props.get("primaryProfession"):
                line += f"  |  professions: {props['primaryProfession']}"
            if props.get("born"):
                line += f"  |  born: {props['born']}"
            if title:
                if props.get("year"):
                    line += f"  ({props['year']})"
                if props.get("genres"):
                    line += f"  |  genres: {props['genres']}"
                if props.get("imdbRating"):
                    line += f"  |  IMDb: {props['imdbRating']}"
                if props.get("plot"):
                    short = props["plot"][:120] + "…" if len(props["plot"]) > 120 else props["plot"]
                    line += f"\n  Plot: {short}"
            lines.append(line)
        lines.append("")

    # Seed nodes
    seed_nodes = data.get("seed_nodes", {}).get("nodes", [])
    if seed_nodes:
        lines.append("## Retrieved Persons / Directors")
        for node in seed_nodes:
            props = node.get("properties", {})
            name = props.get("name", node.get("id", "?"))
            prof = props.get("primaryProfession", "")
            score = node.get("similarity_score", "")
            born = props.get("born", "")
            line = f"- **{name}**"
            if prof:
                line += f"  |  professions: {prof}"
            if born:
                line += f"  |  born: {born}"
            if score:
                line += f"  |  similarity: {score:.4f}"
            lines.append(line)

    # Graph expansion triplets
    triplets = data.get("graph_expansion", {}).get("triplets", [])
    if triplets:
        lines.append("\n## Relationships")
        seen: set[str] = set()
        for t in triplets:
            src_props = t.get("source", {}).get("properties", {})
            tgt_props = t.get("target", {}).get("properties", {})
            rel_type = t.get("relationship", {}).get("type", "?")
            src_name = src_props.get("name", t.get("source", {}).get("id", "?"))
            tgt_title = tgt_props.get("title", tgt_props.get("name", t.get("target", {}).get("id", "?")))
            key = f"{src_name}|{rel_type}|{tgt_title}"
            if key in seen:
                continue
            seen.add(key)
            genre = tgt_props.get("genres", "")
            year = tgt_props.get("year", "")
            rating = tgt_props.get("imdbRating", "")
            plot = tgt_props.get("plot", "")
            line = f"- **{src_name}** [{rel_type}] **{tgt_title}**"
            if year:
                line += f" ({year})"
            if genre:
                line += f"  |  genres: {genre}"
            if rating:
                line += f"  |  IMDb: {rating}"
            if plot:
                short_plot = plot[:120] + "…" if len(plot) > 120 else plot
                line += f"\n  Plot: {short_plot}"
            lines.append(line)

    return "\n".join(lines)


_LONG_TEXT_FIELDS = {"plot", "retrieval_text", "poster", "overview", "description"}

# ---------------------------------------------------------------------------
# Embedding model for re-ranking (same model used by the retrieval pipeline)
# ---------------------------------------------------------------------------

@st.cache_resource
def _get_embed_model():
    """Load the sentence-transformers model, or return None if unavailable."""
    try:
        from sentence_transformers import SentenceTransformer
        return SentenceTransformer("BAAI/bge-small-en-v1.5")
    except Exception as exc:
        st.warning(f"Re-ranking unavailable (embedding model failed to load: {exc}). "
                   "Falling back to truncation.")
        return None


def _node_text(node: dict) -> str:
    """Extract a short representative text from a node for embedding."""
    raw = node.get("retrieval_text", "")
    if raw:
        try:
            rt = json.loads(raw)
            parts = [str(rt.get("title") or rt.get("name") or "")]
            if rt.get("genres"):
                parts.append(str(rt["genres"]))
            if rt.get("plot"):
                parts.append(rt["plot"][:200])
            return " ".join(p for p in parts if p)
        except (json.JSONDecodeError, AttributeError):
            pass
    title = node.get("title") or node.get("name") or ""
    genres = node.get("genres", "")
    plot = node.get("plot", "")[:200]
    return " ".join(p for p in [title, genres, plot] if p)


def rerank_nodes(data: list, query: str, top_k: int = 10) -> list:
    """Return the top_k entries from data ranked by a composite score.

    Composite = 60 % semantic similarity + 40 % normalised IMDb rating.
    Falls back to simple truncation if the embedding model is unavailable.
    """
    if len(data) <= top_k:
        return data

    model = _get_embed_model()
    if model is None:
        return data[:top_k]

    try:
        import numpy as np
        texts = [_node_text(entry.get("n", entry)) for entry in data]
        q_emb = model.encode(query, normalize_embeddings=True)
        t_emb = model.encode(texts, normalize_embeddings=True, show_progress_bar=False)
        sim_scores = t_emb @ q_emb

        ratings = np.array([
            float(entry.get("n", entry).get("imdbRating", 0) or 0) / 10.0
            for entry in data
        ])
        composite = 0.6 * sim_scores + 0.4 * ratings

        top_indices = np.argsort(composite)[::-1][:top_k]
        return [data[i] for i in sorted(top_indices)]
    except Exception as exc:
        st.warning(f"Re-ranking failed ({exc}), falling back to truncation.")
        return data[:top_k]


def build_advanced_rag_context(query: str) -> str:
    """Build readable context from results/retrieved_nodes.json.

    Re-ranks all retrieved nodes by cosine similarity to the query and keeps
    the top 10. When more than 10 nodes remain after re-ranking, long text
    fields (plot, retrieval_text, …) are stripped.
    """
    data = _load_json(_definability_out())
    data = rerank_nodes(data, query, top_k=10)
    compact = len(data) > 10
    lines: list[str] = [f"## Definability-Retrieved Nodes (top {len(data)} re-ranked)"]

    for entry in data:
        node = entry.get("n", entry)
        if compact:
            node = {k: v for k, v in node.items() if k not in _LONG_TEXT_FIELDS}

        name = node.get("name", node.get("id", "?"))
        prof = node.get("primaryProfession", "")
        born = node.get("born", "")
        known = node.get("knownForTitles", "")
        imdb = node.get("imdbId", "")
        title = node.get("title", "")
        genres = node.get("genres", "")
        year = node.get("year", "")
        rating = node.get("imdbRating", "")
        plot = node.get("plot", "")

        # Hop + seed provenance
        hop  = entry.get("hop")
        seed = entry.get("seed", {})
        seed_name  = seed.get("name", "")
        seed_score = seed.get("similarity_score")
        provenance = ""
        if hop is not None:
            provenance += f"hop:{hop}"
        if seed_name:
            provenance += f"  seed:{seed_name}"
            if seed_score is not None:
                provenance += f" (sim {seed_score:.3f})"

        if title:
            line = f"- **{title}**"
            if year:
                line += f" ({year})"
            if genres:
                line += f"  |  genres: {genres}"
            if rating:
                line += f"  |  IMDb: {rating}"
            if provenance:
                line += f"  |  {provenance}"
            if plot:
                short_plot = plot[:120] + "…" if len(plot) > 120 else plot
                line += f"\n  Plot: {short_plot}"
        else:
            line = f"- **{name}**"
            if prof:
                line += f"  |  professions: {prof}"
            if born:
                line += f"  |  born: {born}"
            if imdb:
                line += f"  |  IMDb ID: {imdb}"
            if known:
                line += f"  |  known for: {known}"
            if provenance:
                line += f"  |  {provenance}"

        # Hop nodes — group by rel_type for readability
        hop_nodes = entry.get("hop_nodes", [])
        if hop_nodes:
            by_rel: dict = {}
            for hn in hop_nodes:
                rel  = hn.get("rel_type", "RELATED")
                hnode = hn.get("node", {})
                label = ", ".join(hn.get("labels", []))
                hn_name = (
                    hnode.get("name")
                    or hnode.get("title")
                    or hnode.get("genre")
                    or hnode.get("imdbId", "?")
                )
                born_h   = hnode.get("born", "")
                prof_h   = hnode.get("primaryProfession", "")
                year_h   = hnode.get("year", "")
                rating_h = hnode.get("imdbRating", "")
                genres_h = hnode.get("genres", "")
                detail  = hn_name
                if label:
                    detail += f" [{label}]"
                if born_h:
                    detail += f" b.{born_h}"
                if prof_h:
                    detail += f" ({prof_h})"
                if year_h:
                    detail += f" ({year_h})"
                if rating_h:
                    detail += f" ★{rating_h}"
                if genres_h:
                    detail += f" [{genres_h}]"
                by_rel.setdefault(rel, []).append(detail)

            for rel, names in by_rel.items():
                line += f"\n    {rel}: {', '.join(names)}"

        lines.append(line)

    return "\n".join(lines)


