OLLAMA_BASE = "http://localhost:11434"


def list_ollama_models() -> list[str]:
    try:
        resp = requests.get(f"{OLLAMA_BASE}/api/tags", timeout=5)
        resp.raise_for_status()
        return [m["name"] for m in resp.json().get("models", [])]
    except Exception:
        return []


def ollama_stream(model: str, system: str, user: str):
    """Generator that yields text tokens from a streaming Ollama /api/chat call."""
    payload = {
        "model": model,
        "stream": True,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
    }
    try:
        with requests.post(
            f"{OLLAMA_BASE}/api/chat",
            json=payload,
            stream=True,
            timeout=(10, None),
        ) as resp:
            resp.raise_for_status()
            for raw_line in resp.iter_lines():
                if not raw_line:
                    continue
                chunk = json.loads(raw_line)
                token = chunk.get("message", {}).get("content", "")
                if token:
                    yield token
                if chunk.get("done"):
                    break
    except requests.exceptions.ConnectionError:
        yield "**Error:** Cannot connect to Ollama. Make sure it is running (`ollama serve`)."
    except requests.exceptions.Timeout:
        yield "**Error:** Ollama request timed out."
    except Exception as exc:
        yield f"**Error:** {exc}"


