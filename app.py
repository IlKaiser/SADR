SYSTEM_BASE = (
    "You are a helpful assistant that answers questions about movies, "
    "directors, and the film industry."
)

SYSTEM_WITH_CONTEXT = (
    "You are a helpful assistant that answers questions about movies, "
    "directors, and the film industry. "
    "Use the knowledge-graph context provided to support your answer. "
    "If the context is not directly relevant to the question, still try "
    "to answer as best you can using both the context and your own knowledge."
)


def answer_naive(model: str, question: str):
    yield from ollama_stream(model, SYSTEM_BASE, question)


def answer_simple_rag(model: str, question: str):
    context = build_simple_rag_context()
    user_msg = f"Context (from knowledge-graph retrieval):\n{context}\n\n---\nQuestion: {question}"
    yield from ollama_stream(model, SYSTEM_WITH_CONTEXT, user_msg)


def answer_advanced_rag(model: str, question: str):
    context = build_advanced_rag_context(question)
    user_msg = f"Use the information to answer (from definability-based retrieval):\n{context}\n\n---\nQuestion: {question}"
    yield from ollama_stream(model, SYSTEM_WITH_CONTEXT, user_msg)


