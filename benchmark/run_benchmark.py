"""Retrieval benchmark: dense retrieval, SADR, and Text2Cypher on the public movie graph.

For every question in questions.json the gold set is the result of its hand-written
Cypher query (Movie nodes). Each system returns a set of nodes; only Movie nodes are
scored. Reported per question and system: precision, recall, F1, number of returned
nodes (all labels), and for dense retrieval Recall@k.

Systems:
  dense@5      top-5 nodes of the vector index (the seed set SADR starts from)
  dense@N      top-N nodes, N = size of the SADR-full result (size-matched control)
  sadr_impl    SADR as implemented: seed-node conditions of each disjunct, LIMIT 200
               (with one fix: WHERE clauses on neighbour variables are not kept)
  sadr_full    SADR with the one-hop constraints that carry constants kept as EXISTS
               subqueries, LIMIT 200
  text2cypher  Cypher generated by a local LLM (Ollama) from the question, LIMIT 200

Usage:
    python benchmark/run_benchmark.py --questions benchmark/questions.json \
        --out benchmark/results --model qwen2.5:7b-instruct --k 5
"""

from __future__ import annotations

import argparse
import json
import logging
import re
import time
from dataclasses import dataclass
from pathlib import Path

import requests
from neo4j import READ_ACCESS

import definability as sadr
import text2cypher as t2c

logger = logging.getLogger(__name__)

RESULT_CAP = 200
RANK_DEPTH = 1000  # dense ranking depth, enough to size-match the SADR results
OLLAMA_URL = "http://localhost:11434/api/chat"

# SADR parameters for the public recommendations graph (the same as the defaults of
# definability.py): genres are stored in Genre.name, and RATED edges are excluded
# because they lead to anonymous User nodes.
TARGET_ATTRIBUTES = {"Genre": ["name"], "Movie": ["countries", "year"], "Director": ["name"]}
TARGET_RELATIONS = ["DIRECTED", "IN_GENRE", "ACTED_IN"]

SCHEMA = """Node labels and properties:
  Movie    : id, title, year (int), imdbRating (float), runtime (int), plot,
             countries (LIST of strings, e.g. ["USA", "Japan"]; some entries have a leading space),
             languages (LIST of strings, e.g. ["English", "Japanese"])
  Person   : id, name, born (date)   (every Actor and Director is also a Person)
  Actor    : id, name
  Director : id, name
  Genre    : id, name   (e.g. "Horror", "Animation", "Sci-Fi", "Film-Noir")
Relationships:
  (Actor)-[:ACTED_IN]->(Movie)
  (Director)-[:DIRECTED]->(Movie)
  (Movie)-[:IN_GENRE]->(Genre)
Rules:
  - countries and languages are lists: use any(c IN m.countries WHERE trim(c) = 'Japan')
  - country names are as in IMDb: "USA", "UK", "France", "Japan", "South Korea", "Hong Kong"
  - year is an integer, imdbRating a float, runtime an integer (minutes)"""

T2C_SYSTEM = f"""You are a Neo4j Cypher expert for a movie knowledge graph.
{SCHEMA}
Write ONE read-only Cypher query that returns the movies answering the question.
Return the movie nodes as `RETURN DISTINCT m` and end with `LIMIT {RESULT_CAP}`.
Output only the Cypher query, without explanations or code fences."""


@dataclass(frozen=True)
class Scores:
    precision: float
    recall: float
    f1: float
    returned_movies: int
    returned_nodes: int


def score(retrieved_movies: set[str], returned_nodes: int, gold: set[str]) -> Scores:
    """Precision, recall and F1 of a set of movie ids against the gold set."""
    hit = len(retrieved_movies & gold)
    p = hit / len(retrieved_movies) if retrieved_movies else 0.0
    r = hit / len(gold) if gold else 0.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return Scores(round(p, 4), round(r, 4), round(f, 4), len(retrieved_movies), returned_nodes)


def run_cypher(query: str, params: dict | None = None) -> list[dict]:
    """Run a query in a read-only transaction on the benchmark database."""
    with sadr.driver.session(database=sadr.database, default_access_mode=READ_ACCESS) as session:
        return session.execute_read(lambda tx: tx.run(query, params or {}).data())


def movie_ids(rows: list[dict]) -> tuple[set[str], int]:
    """Movie ids and number of distinct nodes in a result whose nodes are in any column."""
    movies, nodes = set(), set()
    for row in rows:
        for val in row.values():
            if isinstance(val, dict) and "id" in val:
                nodes.add(val["id"])
                if str(val["id"]).startswith("movie_"):
                    movies.add(val["id"])
    return movies, len(nodes)


def gold_set(query: str) -> set[str]:
    """Gold movie ids of a question."""
    return {r["m"]["id"] for r in run_cypher(query)}


class DenseRetriever:
    """Vector search over the 'entity' index with the embedding model of the original pipeline."""

    def __init__(self, model_name: str = "BAAI/bge-small-en-v1.5") -> None:
        from llama_index.embeddings.huggingface import HuggingFaceEmbedding
        self.embed = HuggingFaceEmbedding(model_name=model_name, normalize=True)

    def top(self, question: str, k: int) -> list[dict]:
        """Top-k nodes as [{'id', 'label'}] in rank order."""
        emb = self.embed.get_query_embedding(question)
        rows = run_cypher(
            "CALL db.index.vector.queryNodes('entity', $k, $e) YIELD node, score "
            "RETURN node.id AS id, [l IN labels(node) WHERE l <> '__Entity__'][0] AS label, score",
            {"k": k, "e": emb},
        )
        return rows


def sadr_ucq(seeds: list[dict], workdir: Path) -> str:
    """Synthesize the UCQ of SADR from the seed nodes with the original code."""
    trace = workdir / "seeds.json"
    trace.write_text(json.dumps({"retrieval_mode": "embedding",
                                 "seed_nodes": {"nodes": [{"id": s["id"]} for s in seeds]}}))
    sadr.compute_qbe_ucq(str(trace), workdir)
    return (workdir / "generated_query.txt").read_text()


def split_disjuncts(ucq: str) -> list[list[str]]:
    """Lines of each disjunct, without blank lines and RETURN clauses."""
    out = []
    for part in ucq.split("UNION"):
        lines = [ln.strip() for ln in part.strip().splitlines()]
        out.append([ln for ln in lines if ln and not ln.startswith("RETURN")])
    return [d for d in out if d]


def seed_query(lines: list[str]) -> tuple[str, str]:
    """Seed MATCH line and the WHERE condition on the seed variable only."""
    seed_match, seed_where = "MATCH (n)", ""
    for i, ln in enumerate(lines):
        if re.match(r"^MATCH \(n:[A-Za-z]", ln):
            seed_match = ln
            nxt = lines[i + 1] if i + 1 < len(lines) else ""
            if nxt.startswith("WHERE") and not re.search(r"\bn\d+\.", nxt):
                seed_where = nxt[len("WHERE"):].strip()
            break
    return seed_match, seed_where


def neighbour_constraints(lines: list[str]) -> list[str]:
    """EXISTS subqueries for neighbour variables that carry constant conditions."""
    rels = {}
    for ln in lines:
        for a, rel, b in re.findall(r"\((n\d*)\)-\[:(\w+)\]-\((n\d+)\)", ln):
            if a == "n":
                rels[b] = rel
    labels, conds = {}, {}
    for i, ln in enumerate(lines):
        m = re.match(r"^MATCH \((n\d+):([\w&]+)\)$", ln)
        if m:
            labels[m.group(1)] = m.group(2)
            nxt = lines[i + 1] if i + 1 < len(lines) else ""
            if nxt.startswith("WHERE") and re.search(rf"\b{m.group(1)}\.", nxt):
                conds[m.group(1)] = nxt[len("WHERE"):].strip()
    out = []
    for var, cond in conds.items():
        if var in rels:
            label = labels.get(var, "")
            out.append(f"EXISTS {{ MATCH (n)-[:{rels[var]}]-({var}{':' + label if label else ''}) WHERE {cond} }}")
    return out


def run_sadr(ucq: str, full: bool) -> tuple[set[str], int, list[str]]:
    """Execute every disjunct (seed conditions, plus neighbour constraints if full)."""
    movies, nodes, queries = set(), set(), []
    for lines in split_disjuncts(ucq):
        seed_match, seed_where = seed_query(lines)
        conds = [seed_where] if seed_where else []
        if full:
            conds += neighbour_constraints(lines)
        q = seed_match + (" WHERE " + " AND ".join(conds) if conds else "") + f" RETURN n LIMIT {RESULT_CAP}"
        queries.append(q)
        rows = run_cypher(q)
        m, _ = movie_ids(rows)
        movies |= m
        nodes |= {r["n"]["id"] for r in rows if r["n"].get("id")}
    return movies, len(nodes), queries


def text2cypher(question: str, model: str) -> tuple[set[str], int, str, str]:
    """Generate and run a Cypher query; returns movies, nodes, query and error (if any)."""
    payload = {"model": model, "stream": False, "options": {"temperature": 0},
               "messages": [{"role": "system", "content": T2C_SYSTEM},
                            {"role": "user", "content": question}]}
    query = requests.post(OLLAMA_URL, json=payload, timeout=300).json()["message"]["content"].strip()
    query = re.sub(r"^```\w*|```$", "", query, flags=re.M).strip()
    try:
        rows = t2c.run_cypher(query)  # allowlist, EXPLAIN check, read-only transaction
    except Exception as exc:  # noqa: BLE001 - rejected or failing queries count as failures
        return set(), 0, query, f"{type(exc).__name__}: {str(exc)[:200]}"
    m, n = movie_ids(rows)
    return m, n, query, ""


def main() -> None:
    """Run every system on every question and write per-question results."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--questions", type=Path, default=Path("benchmark/questions.json"))
    parser.add_argument("--out", type=Path, default=Path("benchmark/results"))
    parser.add_argument("--model", default="qwen2.5:7b-instruct")
    parser.add_argument("--k", type=int, default=5)
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    args.out.mkdir(parents=True, exist_ok=True)

    sadr.setup_paramenters()
    sadr.target_attributes = TARGET_ATTRIBUTES
    sadr.target_relations = TARGET_RELATIONS
    dense = DenseRetriever()
    questions = json.loads(args.questions.read_text())
    records, traces = [], []

    for q in questions:
        gold = gold_set(q["gold"])
        ranked = dense.top(q["question"], RANK_DEPTH)
        ranked_movies = [r["id"] for r in ranked if str(r["id"]).startswith("movie_")]
        seeds = ranked[: args.k]
        ucq = sadr_ucq(seeds, args.out)

        t0 = time.time()
        impl_m, impl_n, impl_q = run_sadr(ucq, full=False)
        full_m, full_n, full_q = run_sadr(ucq, full=True)
        t_sadr = time.time() - t0
        t0 = time.time()
        t2c_m, t2c_n, t2c_q, t2c_err = text2cypher(q["question"], args.model)
        t_t2c = time.time() - t0

        size = max(len(full_m), 1)
        systems = {
            f"dense@{args.k}": score({s["id"] for s in seeds if str(s["id"]).startswith("movie_")}, len(seeds), gold),
            "dense@N": score(set(ranked_movies[:size]), len(ranked[: ranked.index(next(r for r in ranked if r["id"] == ranked_movies[min(size, len(ranked_movies)) - 1])) + 1]), gold),
            "sadr_impl": score(impl_m, impl_n, gold),
            "sadr_full": score(full_m, full_n, gold),
            "text2cypher": score(t2c_m, t2c_n, gold),
        }
        for name, s in systems.items():
            records.append({"id": q["id"], "group": q["group"], "system": name, "gold": len(gold), **s.__dict__})
        for k in (5, 10, 20, 50, 100, 200):
            hit = len(set(ranked_movies[:k]) & gold)
            records.append({"id": q["id"], "group": q["group"], "system": f"recall@{k}", "gold": len(gold),
                            "precision": None, "recall": round(hit / len(gold), 4), "f1": None,
                            "returned_movies": min(k, len(ranked_movies)), "returned_nodes": k})
        traces.append({"id": q["id"], "question": q["question"], "gold_size": len(gold),
                       "seeds": seeds, "ucq": ucq, "sadr_impl_queries": impl_q, "sadr_full_queries": full_q,
                       "text2cypher_query": t2c_q, "text2cypher_error": t2c_err,
                       "seconds_sadr": round(t_sadr, 2), "seconds_text2cypher": round(t_t2c, 2)})
        logger.info("%s gold=%d  dense5 R=%.2f  impl P/R=%.2f/%.2f  full P/R=%.2f/%.2f  t2c P/R=%.2f/%.2f %s",
                    q["id"], len(gold), systems[f"dense@{args.k}"].recall,
                    systems["sadr_impl"].precision, systems["sadr_impl"].recall,
                    systems["sadr_full"].precision, systems["sadr_full"].recall,
                    systems["text2cypher"].precision, systems["text2cypher"].recall,
                    "(t2c error)" if t2c_err else "")

    (args.out / "per_question.json").write_text(json.dumps(records, indent=1))
    (args.out / "traces.json").write_text(json.dumps(traces, indent=1, default=str))
    logger.info("Wrote %d records to %s", len(records), args.out)


if __name__ == "__main__":
    main()
